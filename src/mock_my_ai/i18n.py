def normalize_lang(raw: str | None) -> str:
    if not raw:
        return "en"
    v = raw.lower().replace("_", "-")
    if v.startswith("zh"):
        return "zh"
    if v.startswith("en"):
        return "en"
    return "en"


def pick_lang(cookie: str | None, query: str | None, accept_language: str | None) -> str:
    if query in ("en", "zh"):
        return query
    if cookie in ("en", "zh"):
        return cookie
    if accept_language:
        # take first tag
        first = accept_language.split(",")[0].strip()
        return normalize_lang(first)
    return "zh"  # product audience default; browser still wins via Accept-Language


def t(lang: str, key: str, **kwargs: Any) -> str:
    bundle = TRANSLATIONS.get(lang) or TRANSLATIONS["en"]
    text = bundle.get(key) or TRANSLATIONS["en"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


class Translator:
    def __init__(self, lang: str):
        self.lang = lang if lang in TRANSLATIONS else "en"

    def __call__(self, key: str, **kwargs: Any) -> str:
        return t(self.lang, key, **kwargs)

    @property
    def is_zh(self) -> bool:
        return self.lang == "zh"
